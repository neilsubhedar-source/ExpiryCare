// Lightweight Node tests for core batch expiry and transfer rules.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const store = new Map();
const elements = new Map();
const document = { addEventListener(){}, getElementById(id){if(!elements.has(id))elements.set(id,{innerHTML:'',addEventListener(){},value:'',options:[]});return elements.get(id);} };
const context = {window:{},document,localStorage:{getItem:k=>store.get(k)||null,setItem:(k,v)=>store.set(k,v)},sessionStorage:{},console,Date,Math,JSON,Blob:function(){},URL:{},confirm:()=>true};
vm.createContext(context);
vm.runInContext(fs.readFileSync(require('node:path').join(__dirname,'../js/retail-intelligence.js'),'utf8'),context);
const api=context.window.ExpiryCareRetailRules;
assert.ok(api, 'rules export exists');
const d=api.getData();
assert.equal(d.branches.length,3);
assert.ok(d.batches.some(b=>b.expiryDate===null),'unknown expiry demo exists');
assert.ok(d.batches.some(b=>api.days(b)<0),'expired demo exists');
assert.ok(d.batches.filter(api.eligible).every(b=>api.days(b)>=0),'expired and unknown batches excluded from eligible stock');
const src=d.batches.find(b=>b.id==='ba-milk-a');
assert.ok(src.available>0);
assert.throws(()=>api.createTransfer(src.id,src.branchId,1),/differ/,'self-transfer rejected');
assert.throws(()=>api.createTransfer(src.id,'br-b',9999),/exceeds/,'over-allocation rejected');
console.log('Retail rules smoke tests passed.');
// Transfer lifecycle integrity: reserve at approval, deduct once at dispatch, receive once.
const before = api.getData();
const transferBatch = before.batches.find(b => b.id === 'ba-milk-a');
const freeBefore = transferBatch.available - transferBatch.reserved;
api.createTransfer(transferBatch.id, 'br-c', 2);
let state = api.getData();
const transfer = state.transfers[state.transfers.length - 1];
assert.equal(transfer.status, 'Requested');
assert.throws(() => api.transition(transfer.id, 'Receive'), /Invalid/);
api.transition(transfer.id, 'Approve');
state = api.getData();
assert.equal(state.batches.find(b => b.id === transferBatch.id).reserved, 2);
api.transition(transfer.id, 'Dispatch');
state = api.getData();
assert.equal(state.batches.find(b => b.id === transferBatch.id).available, transferBatch.available - 2);
assert.equal(state.batches.find(b => b.id === transferBatch.id).reserved, 0);
assert.throws(() => api.transition(transfer.id, 'Dispatch'), /Invalid/);
api.transition(transfer.id, 'Receive');
state = api.getData();
const destBatch = state.batches.find(b => b.createdFromTransfer === transfer.id);
assert.ok(destBatch, 'received stock is recorded at destination');
assert.equal(destBatch.available, 2);
assert.throws(() => api.transition(transfer.id, 'Receive'), /Invalid/);
api.transition(transfer.id, 'Complete');
assert.equal(api.getData().transfers.find(t => t.id === transfer.id).status, 'Completed');
console.log('Transfer lifecycle integrity tests passed.');
